#!/usr/bin/env python3
"""Write the Homebrew formula of the nexus CLI from a stable release's latest.json.

    render.py formula --manifest cli/stable/latest.json > tap/Formula/nexus-cli.rb

The manifest is the one the release run publishes beside the files on downloads.nexus.inc. The script reads only the
version, the URLs and the sha256 sums, and refuses anything that does not look like a stable release from that host.
"""

import argparse
import json
import re
import sys

HOST = "https://downloads.nexus.inc/"
VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")

FORMULA = """\
# Generated by apps/cli/release/homebrew/render.py in nexus-xyz/nexus-apps. Do not edit by hand.
# Source: {manifest_url}
class NexusCli < Formula
  desc "Command-line client for Nexus, the open-source AI IDE"
  homepage "https://nexus.inc/"
  version "{version}"
  license "MIT"

  # No `livecheck` block: `brew audit` forbids one after the platform blocks and misreads one before them.
  # The release run moves this tap, so nothing needs to detect new versions.
{platforms}
  # homebrew-core's `nexus` (Sonatype Nexus) installs a `nexus` command too.
  conflicts_with "nexus", because: "both install a `nexus` binary"

  def install
    bin.install Dir["nexus-*"].first => "nexus"
  end

  def caveats
    <<~EOS
      Homebrew updates this copy. Run `brew upgrade nexus-cli`, not `nexus update`.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/nexus --version")
  end
end
"""

# Homebrew's OS and CPU blocks, and the CLI target each one downloads.
FORMULA_TARGETS = [
    ("on_macos", "on_arm", "darwin-arm64"),
    ("on_macos", "on_intel", "darwin-x64"),
    ("on_linux", "on_arm", "linux-arm64"),
    ("on_linux", "on_intel", "linux-x64"),
]


def fail(message):
    sys.exit(f"render.py: {message}")


def checked(entry, where):
    url, sha = entry.get("url", ""), entry.get("sha256", "")
    if not url.startswith(HOST):
        fail(f"{where}: url is not on {HOST}: {url!r}")
    if not SHA256.fullmatch(sha):
        fail(f"{where}: sha256 is not 64 hex characters")
    return url, sha


def stable_version(doc):
    version = doc.get("version", "")
    if doc.get("channel") != "stable" or not VERSION.fullmatch(version):
        fail(f"not a stable release: channel={doc.get('channel')!r} version={version!r}")
    return version


def formula(doc, manifest_url):
    version = stable_version(doc)
    targets = doc.get("targets", {})
    blocks = []
    for os_block in ("on_macos", "on_linux"):
        lines = [f"  {os_block} do"]
        for wanted_os, cpu, target in FORMULA_TARGETS:
            if wanted_os != os_block:
                continue
            url, sha = checked(targets.get(target, {}), f"targets.{target}")
            if url != f"{HOST}cli/stable/{version}/nexus-{target}":
                fail(f"unexpected {target} url: {url}")
            lines += [
                f"    {cpu} do",
                f'      url "https://downloads.nexus.inc/cli/stable/#{{version}}/nexus-{target}"',
                f'      sha256 "{sha}"',
                "    end",
            ]
        lines.append("  end")
        blocks.append("\n".join(lines))
    return FORMULA.format(manifest_url=manifest_url, version=version, platforms="\n".join(blocks) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("kind", choices=["formula"])
    ap.add_argument("--manifest", required=True, help="path to the release's latest.json")
    args = ap.parse_args()
    with open(args.manifest, encoding="utf-8") as handle:
        doc = json.load(handle)
    sys.stdout.write(formula(doc, f"{HOST}cli/stable/latest.json"))


if __name__ == "__main__":
    main()
