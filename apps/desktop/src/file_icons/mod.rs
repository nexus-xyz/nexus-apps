//! A file's or a folder's icon from its name, the way an IDE picks it: Material Icon Theme's icons and associations
//! (MIT), with VS Code's built-in languages for the extensions the theme reaches through a language id.
//!
//! The order is VS Code's file icon theme order. For a file: its `parent/name`, its whole name, its extensions from the
//! longest (`d.ts`, then `ts`), the language that claims its name, the language that claims an extension, then the
//! plain file icon. For a folder: its `parent/name`, its name, then the plain folder. Names match in any case.
//!
//! `table.rs` is generated by `scripts/file_icons.py`, which also writes `assets/file_icons/`. The icons are coloured
//! SVGs: draw them with `img`, not `svg`, which would tint them one colour.

#[rustfmt::skip]
mod table;

#[cfg(test)]
mod tests;

use std::borrow::Cow;

use gpui_kit::SharedString;

/// An icon's two variants, as indices into the icon list: the one a dark theme shows and the one a light theme shows.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct Pair {
    dark: u16,
    light: u16,
}

/// A file's or a folder's icon, resolved once from its name. `asset` picks the variant for the theme.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FileIcon(Pair);

impl FileIcon {
    /// The icon of the file at `path` (a name, or a path with `/` or `\`).
    pub fn file(path: &str) -> Self {
        let (parent, name) = split(path);
        let name = name.to_lowercase();
        let found = parent
            .and_then(|parent| find(table::FILE_NAMES, &format!("{}/{name}", parent.to_lowercase())))
            .or_else(|| find(table::FILE_NAMES, &name))
            .or_else(|| extensions(&name).find_map(|extension| find(table::FILE_EXTENSIONS, extension)))
            .or_else(|| find(table::LANGUAGE_NAMES, &name))
            .or_else(|| extensions(&name).find_map(|extension| find(table::LANGUAGE_EXTENSIONS, extension)));
        Self(found.unwrap_or(table::FILE))
    }

    /// The icon of the folder at `path`, open or closed.
    pub fn folder(path: &str, open: bool) -> Self {
        let (parent, name) = split(path);
        let name = name.to_lowercase();
        let key = |name: &str| {
            table::FOLDER_NAMES
                .binary_search_by(|(key, _, _)| (*key).cmp(name))
                .ok()
                .map(|at| table::FOLDER_NAMES[at])
        };
        let found = parent
            .and_then(|parent| key(&format!("{}/{name}", parent.to_lowercase())))
            .or_else(|| key(&name));
        Self(match (found, open) {
            (Some((_, closed, _)), false) => closed,
            (Some((_, _, opened)), true) => opened,
            (None, false) => table::FOLDER,
            (None, true) => table::FOLDER_OPEN,
        })
    }

    /// The icon's asset path for a dark or a light theme, for `img`.
    pub fn asset(self, dark: bool) -> SharedString {
        let index = if dark { self.0.dark } else { self.0.light };
        SharedString::new_static(table::ICONS[usize::from(index)].0)
    }
}

/// The SVG of an icon by its asset path (`file_icons/rust.svg`), for the app's `AssetSource`.
pub fn load(path: &str) -> Option<Cow<'static, [u8]>> {
    table::ICONS
        .binary_search_by(|(asset, _)| (*asset).cmp(path))
        .ok()
        .map(|at| Cow::Borrowed(table::ICONS[at].1))
}

fn find(table: &[(&str, Pair)], key: &str) -> Option<Pair> {
    table
        .binary_search_by(|(entry, _)| (*entry).cmp(key))
        .ok()
        .map(|at| table[at].1)
}

/// A path's parent folder name, if it has one, and its own name. A trailing separator is ignored.
fn split(path: &str) -> (Option<&str>, &str) {
    let mut parts = path.rsplit(['/', '\\']).filter(|part| !part.is_empty());
    let name = parts.next().unwrap_or("");
    (parts.next(), name)
}

/// A name's extensions from the longest, as VS Code reads them: `a.b.c` has `b.c` and `c`, and `.eslintrc.json` has
/// `eslintrc.json` and `json`.
fn extensions(name: &str) -> impl Iterator<Item = &str> {
    name.match_indices('.')
        .map(move |(at, _)| &name[at + 1..])
        .filter(|extension| !extension.is_empty())
}
